import { expect, test } from 'bun:test';
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

const rootHook = readFileSync(resolve(import.meta.dir, '../../lefthook.yml'), 'utf8');
const checker = (await import('./check-domain-contracts')) as unknown as {
  verifyGeneratedModule?: (
    path: string,
    text: string,
    expectation: { provenance: RegExp; requiredExports: readonly string[] },
    expectedSourceHash?: string,
  ) => string[];
};

test('domain contract hook watches source gitlinks and their nested files', () => {
  const glob = rootHook.match(/domain-contract-guardrails:\n\s+glob:\s+"([^"]+)"/)?.[1];
  expect(glob).toBeDefined();
  const patterns = new Set((glob?.slice(1, -1) ?? '').split(','));

  for (const path of ['chronicle-api', 'chronicle-models', 'chronicle-web']) {
    expect(patterns).toContain(path);
  }
  for (const path of [
    'chronicle-api/chronicle.yaml',
    'chronicle-models/**',
    'chronicle-web/src/modern/generated/**',
    'chronicle-web/src/modern/types/**',
  ]) {
    expect(patterns).toContain(path);
  }
});

test('rejects source-only drift even when generated content integrity remains valid', () => {
  const sourceHashInArtifact = 'a'.repeat(64);
  const currentSourceHash = 'b'.repeat(64);
  const body = 'export const PAYLOAD_FIXTURE_REGISTRY = {};\nexport const PAYLOAD_FIXTURES = {};\n';
  const contentHash = createHash('sha256').update(body, 'utf-8').digest('hex');
  const generated = [
    '// Generated by scripts/generate-chronicle-payload-contracts.py from chronicle-api and chronicle-models fixtures.',
    `// Source-SHA256: ${sourceHashInArtifact}`,
    `// Content-SHA256: ${contentHash}`,
    '// Do not edit by hand.',
    body,
  ].join('\n');
  const path = 'synthetic/chronicle-payload-contracts.generated.ts';
  const errors = checker.verifyGeneratedModule?.(
    path,
    generated,
    {
      provenance: /^\/\/ Generated by scripts\/generate-chronicle-payload-contracts\.py from chronicle-api and chronicle-models fixtures\./m,
      requiredExports: ['PAYLOAD_FIXTURE_REGISTRY', 'PAYLOAD_FIXTURES'],
    },
    currentSourceHash,
  ) ?? [];

  expect(errors).toContain(
    `${path}: Source-SHA256 mismatch: generated artifact uses ${sourceHashInArtifact}, current sources hash to ${currentSourceHash}`,
  );
});
